class FrozenMethod(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.model = est.fit(rows(), method=est.DEFAULT_METHOD)

    def assertClose(self, actual, expected):
        self.assertTrue(
            math.isclose(actual, expected, rel_tol=REL, abs_tol=0.0),
            f"{actual!r} != {expected!r}",
        )

    def test_the_fixture_covers_every_query(self):
        self.assertEqual(set(LOCATED), set(QUERIES))
        self.assertEqual(set(CELL_QUANTILES), set(QUERIES))
        self.assertEqual(set(TASK_P50), {task.id for task in plan_tasks()})

    def test_located_cells(self):
        for name, query in QUERIES.items():
            with self.subTest(query=name):
                cell = self.model.locate(query)
                mu, v, n, n_eff, label, pooled_from, thin = LOCATED[name]
                self.assertClose(cell.mu, mu)
                self.assertClose(cell.v, v)
                self.assertEqual(cell.n, n)
                self.assertClose(cell.n_eff, n_eff)
                self.assertEqual(cell.label, label)
                self.assertEqual(cell.pooled_from, pooled_from)
                self.assertIs(cell.thin, thin)

    def test_cell_quantiles(self):
        for name, query in QUERIES.items():
            with self.subTest(query=name):
                actual = est.cell_quantiles(self.model, query, 2000, random.Random(1))
                for value, expected in zip(actual, CELL_QUANTILES[name], strict=True):
                    self.assertClose(value, expected)

    def test_plan(self):
        plan = est.estimate(self.model, plan_tasks(), agent_cap=2, draws=2000, seed=5)
        for value, expected in zip((plan.p50, plan.p80, plan.p90), PLAN, strict=True):
            self.assertClose(value, expected)
        self.assertEqual([task.id for task in plan.tasks], [task.id for task in plan_tasks()])
        for task in plan.tasks:
            with self.subTest(task=task.id):
                self.assertClose(task.p50, TASK_P50[task.id])

    def test_a_canonical_plan_document_equals_its_tasks(self):
        tasks, cap = est.tasks_from_json(CANONICAL_DOCUMENT)
        self.assertEqual(cap, 2)

        def fields(task):
            return (task.id, task.kind, task.risk, task.size, task.model, task.depends_on)

        self.assertEqual([fields(task) for task in tasks], [fields(t) for t in CANONICAL_TASKS])
        through_document = est.estimate(self.model, tasks, cap, draws=2000, seed=5)
        direct = est.estimate(self.model, CANONICAL_TASKS, 2, draws=2000, seed=5)
        self.assertEqual(through_document, direct)


