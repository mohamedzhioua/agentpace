HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
PROTOCOL = HERE / "PROTOCOL.md"
REGISTERED_AT = "ed9f597"
INCUMBENT = offset.INCUMBENT
HARNESS = "claude-code"
CODEX = "codex"
QUERY = ("task_kind", "risk", "model", "size")

STREAM = f"{backtest.SEED}:{NAME}:False"
INTERVALS_STREAM = f"{backtest.SEED}:{NAME}:intervals"
# PROTOCOL "Win rule", G1: the affected sessions' interval uses "a second `Random` with suffix
# `:affected`". It can read as `f"{SEED}:model-offset-v1:affected"` (the suffix in place of
# `:intervals`) or `f"{SEED}:model-offset-v1:intervals:affected"` (appended). Left unset until
# ruled; nothing reaches it before a Claude Code session is affected.
AFFECTED_INTERVALS_STREAM: str | None = None
# PROTOCOL "Win rule", decision: "lose" when "G1's lower end is above zero". G1 holds two
# intervals: the reading may be "all" (the all-sessions interval), "both" or "either". Left
# unset until ruled; nothing reaches it before G0 holds.
LOSE_WHEN: str | None = None

MIN_AFFECTED_SESSIONS = 10
MIN_AFFECTED_ROWS = 50
MIN_CODEX_ROWS = 50
COVERAGE_SLACK = 5.0
LOSS_RATIO = 1.05
CLOSING_WEEK = "2026-W52"
AWAITING = "awaiting the first qualifying data change"
GATES = ("G0", "G1", "G2", "G3", "G4")
METRICS = ("coverage50", "coverage80", "coverage90", "width", "pinball")

_NOTE = "<!-- Generated by `python -m experiments.model_offset`. Do not edit by hand. -->"


class NeedsRuling(RuntimeError):
    """A point `PROTOCOL.md` leaves open. It is ruled on, never chosen here."""


@dataclass(frozen=True)
class Held:
    """One held-out completed row with both forecasts."""

    row: Row
    ours: Forecast
    theirs: Forecast
    affected: bool


def digest(paths: Sequence[Path]) -> str:
    """sha256 over file names and contents, line endings normalized, so every OS agrees."""
    found = hashlib.sha256()
    for path in paths:
        body = path.read_bytes().replace(b"\r\n", b"\n")
        found.update(f"{path.name}\n{len(body)}\n".encode())
        found.update(body)
    return found.hexdigest()


def split(rows: Sequence[Row], last_week: str) -> tuple[list[Fold], list[Fold]]:
    """`backtest.time_folds` over every row, split as `backtest.run` splits them."""
    usable = [dict(row) for row in rows]
    for row in usable:
        row.setdefault("project", "")
    every_week = backtest.time_folds(usable)
    time = [fold for fold in every_week if fold.name <= last_week]
    locked = [fold for fold in every_week if fold.name > last_week]
    return time, locked


def challenger(
    folds: Sequence[Fold],
) -> tuple[list[OffsetModel], list[list[Forecast]], list[list[bool]]]:
    """`backtest._candidate`'s loop with the offset model, one stream across the folds in order.
    Also whether each row's `Located` differs from the incumbent's."""
    rng = random.Random(STREAM)
    models: list[OffsetModel] = []
    forecasts: list[list[Forecast]] = []
    affected: list[list[bool]] = []
    for fold in folds:
        model = offset.fit(fold.train)
        cache: dict[tuple[str, ...], tuple[float, float, float]] = {}
        differs: dict[tuple[str, ...], bool] = {}
        items: list[Forecast] = []
        flags: list[bool] = []
        for row in backtest._completed(fold.test):
            query = {name: row[name] for name in QUERY}
            key = tuple(query.values())
            if key not in cache:
                cache[key] = est.cell_quantiles(model, query, backtest.CELL_DRAWS, rng)
                differs[key] = model.locate(query) != model.incumbent(query)
            p50, p80, p90 = cache[key]
            items.append(Forecast(p50, p80, p90, row["duration_s"], row["batch"], row["harness"]))
            flags.append(differs[key])
        models.append(model)
        forecasts.append(items)
        affected.append(flags)
    return models, forecasts, affected


def challenger_plans(locked: Sequence[Fold], models: Sequence[OffsetModel]) -> list[Forecast]:
    """`backtest.plan_forecasts`'s loop with the offset model, Claude Code sessions only."""
    plans: list[Forecast] = []
    for fold, model in zip(locked, models, strict=True):
        for batch, members in sorted(backtest._sessions(backtest._completed(fold.test)).items()):
            if len(members) < est.MIN_SESSION_RUNS or members[0]["harness"] != HARNESS:
                continue
            tasks = [
                est.Task(str(i), row["task_kind"], row["risk"], model=row["model"])
                for i, row in enumerate(members)
            ]
            cap = max(row["parallel_agents"] for row in members)
            plan = est.estimate(model, tasks, cap, backtest.PLAN_DRAWS, backtest.SEED)
            first = min(row["offset_s"] for row in members)
            actual = max(row["offset_s"] + row["duration_s"] for row in members) - first
            plans.append(Forecast(plan.p50, plan.p80, plan.p90, max(actual, 1), batch))
    return plans


def _summary(forecasts: Sequence[Forecast]) -> dict[str, dict[str, float]] | None:
    if not forecasts:
        return None
    found = backtest.both_weightings(forecasts)
    return {weighting: {key: found[weighting][key] for key in METRICS} for weighting in found}


def _paired(ours: list[Forecast], theirs: list[Forecast], seed: str) -> list[float]:
    found = backtest.intervals(
        {INCUMBENT: ours, NAME: theirs}, INCUMBENT, [NAME], random.Random(seed)
    )
    return list(found["rival_minus_ours"][NAME])


def _affected_table(held: Sequence[Held]) -> list[dict[str, Any]]:
    rows: dict[tuple[str, ...], int] = defaultdict(int)
    sessions: dict[tuple[str, ...], set[str]] = defaultdict(set)
    for item in held:
        if item.affected:
            key = tuple(item.row[name] for name in ("harness", "task_kind", "risk", "model"))
            rows[key] += 1
            sessions[key].add(item.row["batch"])
    return [
        {
            "harness": key[0],
            "task_kind": key[1],
            "risk": key[2],
            "model": key[3],
            "rows": rows[key],
            "sessions": len(sessions[key]),
        }
        for key in sorted(rows)
    ]


def _by_harness(held: Sequence[Held]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for harness in sorted({item.row["harness"] for item in held}):
        mine = [item for item in held if item.row["harness"] == harness]
        ours = backtest.both_weightings([item.ours for item in mine])
        theirs = backtest.both_weightings([item.theirs for item in mine])
        result[harness] = {
            "sessions": len({item.row["batch"] for item in mine}),
            "rows": len(mine),
            "affected_rows": sum(item.affected for item in mine),
            "affected_sessions": len({item.row["batch"] for item in mine if item.affected}),
            **{
                name: {
                    "pinball_row": found["row"]["pinball"],
                    "pinball_session": found["session"]["pinball"],
                    "coverage80_session": found["session"]["coverage80"],
                }
                for name, found in ((INCUMBENT, ours), (NAME, theirs))
            },
        }
    return result


def _locked(
    locked: Sequence[Fold],
    models: Sequence[OffsetModel],
    held: Sequence[Held],
    plans: dict[str, list[Forecast]],
) -> dict[str, Any]:
    ours = [item for item in held if item.row["harness"] == HARNESS]
    hit = {item.row["batch"] for item in ours if item.affected}
    touched = [item for item in ours if item.row["batch"] in hit]
    interval_all = (
        _paired([i.ours for i in ours], [i.theirs for i in ours], INTERVALS_STREAM)
        if ours
        else None
    )
    interval_affected = None
    if touched:
        if AFFECTED_INTERVALS_STREAM is None:
            raise NeedsRuling(
                "PROTOCOL.md G1: which seed string is 'a second Random with suffix :affected'?"
            )
        interval_affected = _paired(
            [i.ours for i in touched], [i.theirs for i in touched], AFFECTED_INTERVALS_STREAM
        )
    return {
        "status": "ok",
        "folds": [
            {
                "week": fold.name,
                "train_rows": len(fold.train),
                "test_rows": len(fold.test),
                "forecast_rows": len(backtest._completed(fold.test)),
            }
            for fold in locked
        ],
        "affected": {
            "rows": sum(item.affected for item in held),
            "sessions": len({item.row["batch"] for item in held if item.affected}),
            "claude_code_rows": sum(item.affected for item in ours),
            "claude_code_sessions": len(hit),
            "cells": _affected_table(held),
        },
        "beta": [
            {
                "week": fold.name,
                "rows": model.rows,
                "s2": model.s2,
                "models": [
                    {"model": name, "beta": model.beta[name], "se": se}
                    for name, se in offset.standard_errors(model).items()
                ],
            }
            for fold, model in zip(locked, models, strict=True)
        ],
        "tasks": {
            "claude_code": {
                "rows": len(ours),
                "sessions": len({item.row["batch"] for item in ours}),
                INCUMBENT: _summary([item.ours for item in ours]),
                NAME: _summary([item.theirs for item in ours]),
            },
            "affected_sessions": {
                "rows": len(touched),
                "sessions": len(hit),
                INCUMBENT: _summary([item.ours for item in touched]),
                NAME: _summary([item.theirs for item in touched]),
            },
        },
        "intervals": {"claude_code": interval_all, "affected_sessions": interval_affected},
        "plans": {
            "label": "oracle-structure",
            "sessions": len(plans[INCUMBENT]),
            INCUMBENT: _summary(plans[INCUMBENT]),
            NAME: _summary(plans[NAME]),
        },
        "by_harness": _by_harness(held),
    }


def _empty_locked(last_week: str) -> dict[str, Any]:
    return {
        "status": f"no weeks after {last_week} yet",
        "folds": [],
        "affected": {
            "rows": 0,
            "sessions": 0,
            "claude_code_rows": 0,
            "claude_code_sessions": 0,
            "cells": [],
        },
    }


def gates(backtest_status: str, locked: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """Each gate as pass, fail or not evaluable, with what it found."""
    affected = locked["affected"]
    sessions, rows = affected["claude_code_sessions"], affected["claude_code_rows"]
    g0 = backtest_status == "ok" and sessions >= MIN_AFFECTED_SESSIONS and rows >= MIN_AFFECTED_ROWS
    result: dict[str, dict[str, Any]] = {
        "G0": {
            "result": "pass" if g0 else "fail",
            "backtest_locked_status": backtest_status,
            "affected_claude_code_sessions": sessions,
            "affected_claude_code_rows": rows,
        }
    }
    found = locked.get("intervals", {})
    both = [found.get("claude_code"), found.get("affected_sessions")]
    if all(interval is not None for interval in both):
        upper = all(interval[1] < 0 for interval in both)
        result["G1"] = {"result": "pass" if upper else "fail", "intervals": both}
    else:
        result["G1"] = {"result": "not evaluable", "intervals": both}

    tasks = locked.get("tasks", {}).get("claude_code", {})
    ours, theirs = tasks.get(INCUMBENT), tasks.get(NAME)
    if ours is None or theirs is None:
        result["G2"] = {"result": "not evaluable"}
    else:
        levels = {
            level: [theirs["session"][level], ours["session"][level]]
            for level in ("coverage80", "coverage90")
        }
        held = all(mine >= base - COVERAGE_SLACK for mine, base in levels.values())
        result["G2"] = {"result": "pass" if held else "fail", **levels}

    plans = locked.get("plans", {})
    ours, theirs = plans.get(INCUMBENT), plans.get(NAME)
    if ours is None or theirs is None:
        result["G3"] = {"result": "not evaluable"}
    else:
        pair = [theirs["row"]["pinball"], ours["row"]["pinball"]]
        held = pair[0] <= LOSS_RATIO * pair[1]
        result["G3"] = {"result": "pass" if held else "fail", "pinball": pair}

    codex = locked.get("by_harness", {}).get(CODEX)
    codex_rows = 0 if codex is None else codex["rows"]
    if codex is None or codex_rows < MIN_CODEX_ROWS:
        result["G4"] = {"result": "not evaluable", "codex_rows": codex_rows}
    else:
        pair = [codex[NAME]["pinball_row"], codex[INCUMBENT]["pinball_row"]]
        held = pair[0] <= LOSS_RATIO * pair[1]
        result["G4"] = {
            "result": "pass" if held else "fail",
            "codex_rows": codex_rows,
            "pinball": pair,
        }
    return result


def _lose(found: dict[str, dict[str, Any]]) -> bool:
    """Every lower end LOSE_WHEN names is above zero."""
    every, touched = (float(interval[0]) for interval in found["G1"]["intervals"])
    named = {"all": [every], "both": [every, touched], "either": [max(every, touched)]}
    if LOSE_WHEN is None:
        raise NeedsRuling("PROTOCOL.md decision: which interval is 'G1's lower end'?")
    return all(lower > 0 for lower in named[LOSE_WHEN])


def decide(
    found: dict[str, dict[str, Any]],
    latest_week: str,
    data_sha256: str,
    stored: dict[str, Any] | None,
) -> dict[str, Any]:
    """Once per data change, and never again after the experiment closes."""
    if stored is not None and stored.get("status") == "closed":
        return stored
    if found["G0"]["result"] == "pass":
        holds = all(
            found[name]["result"] == "pass"
            or (name == "G4" and found[name]["result"] == "not evaluable")
            for name in ("G1", "G2", "G3", "G4")
        )
        if holds:
            outcome = "win"
        elif found["G1"]["result"] != "not evaluable" and _lose(found):
            outcome = "lose"
        else:
            outcome = "not shown"
    elif latest_week >= CLOSING_WEEK:
        outcome = "not testable"
    else:
        return {"status": "open", "line": AWAITING}
    return {
        "status": "closed",
        "outcome": outcome,
        "line": f"{outcome}, closed",
        "latest_week": latest_week,
        "data_sha256": data_sha256,
        "gates": {name: found[name]["result"] for name in GATES},
    }


def build(
    rows: Sequence[Row],
    backtest_status: str,
    data_sha256: str,
    stored: dict[str, Any] | None = None,
    last_week: str = backtest.SELECTION_LAST_WEEK,
) -> dict[str, Any]:
    """Everything `report.md` and `report.json` say."""
    time, locked = split(rows, last_week)
    folds = [*time, *locked]
    models, theirs, affected = challenger(folds)
    if locked:
        ours = backtest._forecast_folds(folds, False, backtest.SEED)[INCUMBENT]
        later = range(len(time), len(folds))
        held = []
        for i in later:
            completed = backtest._completed(folds[i].test)
            for row, mine, other, flag in zip(
                completed, ours[i], theirs[i], affected[i], strict=True
            ):
                assert (mine.actual, mine.session) == (other.actual, other.session)
                held.append(Held(row, mine, other, flag))
        plans = {
            INCUMBENT: backtest.plan_forecasts(locked, INCUMBENT, backtest.SEED, HARNESS)[
                "agentpace"
            ],
            NAME: challenger_plans(locked, models[len(time) :]),
        }
        locked_result = _locked(locked, models[len(time) :], held, plans)
    else:
        locked_result = _empty_locked(last_week)
    found = gates(backtest_status, locked_result)
    latest_week = max(row["week"] for row in rows)
    return {
        "protocol": {
            "name": NAME,
            "registered_at": REGISTERED_AT,
            "sha256": digest([PROTOCOL]),
        },
        "selection_last_week": last_week,
        "incumbent": INCUMBENT,
        "seed": backtest.SEED,
        "data": {
            "rows": len(rows),
            "latest_week": latest_week,
            "sha256": data_sha256,
        },
        "selection_folds": len(time),
        "backtest_locked_status": backtest_status,
        "locked": locked_result,
        "gates": found,
        "decision": decide(found, latest_week, data_sha256, stored),
    }


def _pct(value: float) -> str:
    return f"{value:.1f}%"


def _interval(found: list[float] | None) -> str:
    return "not evaluable" if found is None else f"{found[0]:+.0f} to {found[1]:+.0f}"


def _metric_lines(block: dict[str, Any]) -> list[str]:
    lines = [
        "| Method | Weighting | P50 cov. | P80 cov. | P90 cov. | P90/P50 | Pinball |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for name in (INCUMBENT, NAME):
        found = block[name]
        if found is None:
            continue
        for weighting in ("session", "row"):
            m = found[weighting]
            lines.append(
                f"| {name} | {weighting} | {_pct(m['coverage50'])} | {_pct(m['coverage80'])} | "
                f"{_pct(m['coverage90'])} | {m['width']:.1f}x | {m['pinball']:.0f} |"
            )
    return lines


def _gate_lines(found: dict[str, dict[str, Any]]) -> list[str]:
    g0 = found["G0"]
    details = {
        "G0": (
            f"`docs/backtest.json` locked status: {g0['backtest_locked_status']}; "
            f"{g0['affected_claude_code_sessions']} of {MIN_AFFECTED_SESSIONS} affected Claude "
            f"Code sessions; {g0['affected_claude_code_rows']} of {MIN_AFFECTED_ROWS} affected "
            "Claude Code rows"
        ),
        "G1": (
            f"challenger minus `{INCUMBENT}`, session pinball: Claude Code "
            f"{_interval(found['G1']['intervals'][0])}; affected sessions "
            f"{_interval(found['G1']['intervals'][1])}; both upper ends must be below zero"
        ),
        "G2": "no Claude Code locked rows",
        "G3": "no locked Claude Code session with 5+ completed runs",
        "G4": f"{found['G4']['codex_rows']} Codex locked rows, {MIN_CODEX_ROWS} needed",
    }
    if "coverage80" in found["G2"]:
        p80, p90 = found["G2"]["coverage80"], found["G2"]["coverage90"]
        details["G2"] = (
            f"session-weighted P80 {_pct(p80[0])} against {_pct(p80[1])}, P90 {_pct(p90[0])} "
            f"against {_pct(p90[1])}; at most {COVERAGE_SLACK:.0f} points below"
        )
    if "pinball" in found["G3"]:
        mine, base = found["G3"]["pinball"]
        details["G3"] = f"row-weighted plan pinball {mine:.0f} against {base:.0f}, at most 1.05x"
    if "pinball" in found["G4"]:
        mine, base = found["G4"]["pinball"]
        details["G4"] = (
            f"{found['G4']['codex_rows']} Codex locked rows; row-weighted pinball {mine:.0f} "
            f"against {base:.0f}, at most 1.05x"
        )
    lines = ["| Gate | Result | Found |", "|---|---|---|"]
    lines += [f"| {name} | {found[name]['result']} | {details[name]} |" for name in GATES]
    return lines


def _decision_line(decision: dict[str, Any]) -> str:
    if decision["status"] != "closed":
        return f"**Decision: {decision['line']}.**"
    return (
        f"**Decision: {decision['outcome']}.** Closed at the data change with latest week "
        f"{decision['latest_week']} (`data/runs` sha256 `{decision['data_sha256']}`), with gates "
        + ", ".join(f"{name} {result}" for name, result in decision["gates"].items())
        + ". Stored in `report.json` and reprinted, never re-decided."
    )


def _locked_lines(locked: dict[str, Any], last_week: str) -> list[str]:
    affected = locked["affected"]
    counts = (
        f"Affected rows: {affected['rows']} ({affected['claude_code_rows']} Claude Code). "
        f"Affected sessions: {affected['sessions']} ({affected['claude_code_sessions']} Claude "
        "Code)."
    )
    lines = [
        "## Locked holdout",
        "",
        f"Weeks after {last_week}. A row is affected when the challenger's cell differs from the "
        f"incumbent's; a session is affected when any of its rows is.",
        "",
    ]
    if locked["status"] != "ok":
        status = locked["status"]
        return [*lines, f"**{status[0].upper()}{status[1:]}.** {counts}", ""]
    lines += [
        "| Week | Train rows | Test rows | Forecast rows |",
        "|---|---:|---:|---:|",
        *(
            f"| {f['week']} | {f['train_rows']:,} | {f['test_rows']:,} | {f['forecast_rows']:,} |"
            for f in locked["folds"]
        ),
        "",
        counts,
        "",
    ]
    if affected["cells"]:
        lines += [
            "| Harness | Kind | Risk | Model | Affected rows | Affected sessions |",
            "|---|---|---|---|---:|---:|",
            *(
                f"| {c['harness']} | {c['task_kind']} | {c['risk']} | {c['model']} | "
                f"{c['rows']} | {c['sessions']} |"
                for c in affected["cells"]
            ),
            "",
        ]
    lines += [
        "### Offsets",
        "",
        "`beta` per model with `sqrt(diag C)`, per locked fold. It is a log-scale offset inside "
        "a kind and risk, confounded with what each model was given; it is not model speed.",
        "",
        "| Week | Model | beta | sqrt(C) |",
        "|---|---|---:|---:|",
    ]
    for fold in locked["beta"]:
        for m in fold["models"]:
            lines.append(f"| {fold['week']} | {m['model']} | {m['beta']:+.3f} | {m['se']:.3f} |")
    lines.append("")
    for key, title in (
        ("claude_code", "Claude Code locked rows"),
        ("affected_sessions", "Affected Claude Code sessions"),
    ):
        block = locked["tasks"][key]
        lines += [f"### {title}", "", f"{block['sessions']} sessions, {block['rows']} rows.", ""]
        if block[INCUMBENT] is not None:
            lines += [*_metric_lines(block), ""]
    intervals = locked["intervals"]
    lines += [
        "### Paired intervals",
        "",
        f"Challenger minus `{INCUMBENT}`, session-weighted pinball, 95% session bootstrap: "
        f"Claude Code locked rows {_interval(intervals['claude_code'])}; affected sessions "
        f"{_interval(intervals['affected_sessions'])}.",
        "",
    ]
    plans = locked["plans"]
    lines += [
        "### Whole sessions (oracle-structure)",
        "",
        f"Locked Claude Code sessions with {est.MIN_SESSION_RUNS}+ completed runs: "
        f"{plans['sessions']}. The observed peak concurrency stands in for the cap and the "
        "longest run for the critical path.",
        "",
    ]
    if plans[INCUMBENT] is not None:
        lines += [*_metric_lines(plans), ""]
    lines += [
        "### By harness",
        "",
        "| Harness | Sessions | Rows | Affected rows | Method | Pinball, row | "
        "Pinball, session | P80 cov., session |",
        "|---|---:|---:|---:|---|---:|---:|---:|",
    ]
    for harness, h in locked["by_harness"].items():
        for name in (INCUMBENT, NAME):
            m = h[name]
            lines.append(
                f"| {harness} | {h['sessions']} | {h['rows']} | {h['affected_rows']} | {name} | "
                f"{m['pinball_row']:.0f} | {m['pinball_session']:.0f} | "
                f"{_pct(m['coverage80_session'])} |"
            )
    lines.append("")
    return lines


def markdown(report: dict[str, Any]) -> str:
    """Rendered from the rounded JSON, so the two files never disagree in the last digit."""
    protocol, data = report["protocol"], report["data"]
    last_week = report["selection_last_week"]
    lines = [
        _NOTE,
        f"# Experiment `{protocol['name']}`",
        "",
        f"Protocol `{protocol['name']}`, registered on `main` at `{protocol['registered_at']}` "
        f"and frozen in [PROTOCOL.md](PROTOCOL.md) (sha256 `{protocol['sha256']}`). A challenger "
        f"to `{report['incumbent']}`, scored on the locked holdout only, with its own random "
        f"streams (seed {report['seed']}). No number here enters the README, the site, a claim "
        "or `docs/backtest.*`.",
        "",
        f"Data: {data['rows']:,} runs in `data/runs/`, latest week {data['latest_week']}, "
        f"sha256 `{data['sha256']}`.",
        "",
        f"`SELECTION_LAST_WEEK` is {last_week}. The {report['selection_folds']} time folds up "
        "to it are forecast so the challenger's stream is consumed in order; they are never "
        "scored or printed.",
        "",
        "## Decision",
        "",
        _decision_line(report["decision"]),
        "",
        "## Gates",
        "",
        *_gate_lines(report["gates"]),
        "",
        *_locked_lines(report["locked"], last_week),
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


def render(report: dict[str, Any]) -> tuple[str, str]:
    """`report.json` and `report.md`, both from the rounded numbers."""
    text = published.to_json(report)
    return text, markdown(json.loads(text))


def _stored_decision(path: Path) -> dict[str, Any] | None:
    try:
        decision = json.loads(path.read_text(encoding="utf-8"))["decision"]
    except (OSError, ValueError, KeyError, TypeError):
        return None
    return decision if isinstance(decision, dict) else None


def _backtest_status(path: Path) -> str:
    status = json.loads(path.read_text(encoding="utf-8"))["locked"]["status"]
    return str(status)


def main(argv: Sequence[str] | None = None, root: Path = REPO, out: Path = HERE) -> int:
    parser = argparse.ArgumentParser(prog="python -m experiments.model_offset")
    parser.add_argument("--check", action="store_true", help="fail if the report is stale")
    args = parser.parse_args(argv)
    data = root / "data" / "runs"
    files = sorted(data.glob("*.jsonl"))
    rows = schema.read_dataset(files)
    if not rows:
        raise SystemExit(f"no rows in {data}")
    report = build(
        rows,
        _backtest_status(root / "docs" / "backtest.json"),
        digest(files),
        _stored_decision(out / "report.json"),
    )
    json_text, md_text = render(report)
    targets = {out / "report.json": json_text, out / "report.md": md_text}
    if args.check:
        stale = [
            path.name
            for path, text in targets.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            print(
                f"{NAME} report differs from a regeneration: {', '.join(stale)}",
                file=sys.stderr,
            )
            return 1
        print(f"{NAME} report matches the data")
        return 0
    for path, text in targets.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out / 'report.md'}; decision: {report['decision']['line']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
