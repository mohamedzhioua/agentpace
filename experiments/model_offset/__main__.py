"""Generate `report.md` and `report.json` for `model-offset-v1`, or check them with `--check`.

    PYTHONPATH=src python -m experiments.model_offset [--check]

Everything follows `PROTOCOL.md`: the folds `agentpace backtest` uses, the challenger's own
stream in fold order (selection folds are forecast and never scored or printed), the incumbent's
forecasts from `backtest._forecast_folds`, the gates and the decision rule. A closed decision is
stored in `report.json` with the data it was made on and reprinted, never re-decided.
"""

